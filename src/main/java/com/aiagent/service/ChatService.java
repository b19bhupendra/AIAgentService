package com.aiagent.service;

import com.aiagent.dto.InterviewQuestionsResponse;
import jakarta.validation.ConstraintViolation;
import jakarta.validation.ConstraintViolationException;
import jakarta.validation.Validator;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.stereotype.Service;

import java.util.Set;

@Service
public class ChatService {
    //ChatClient — Spring AI abstraction for interacting with the LLM.
    private final ChatClient chatClient;

    private final Validator validator;

    //ChatClient.Builder — Spring AI automatically configures this using our Gemini dependency and properties.
    public ChatService(ChatClient.Builder builder, Validator validator){
        this.chatClient = builder.build();
        this.validator = validator;
    }

    public String chat(String message){
        //.prompt() —starts a new prompt,user(message) —supplies the user's message,call() —sends the request to Gemini,content() — extracts the generated text.
        return chatClient.prompt()
                // System message: Defines AI behaviour
                .system("""
                        You are an experienced Java technical interviewer.

                        Your responsibilities:
                        1. Generate technically accurate Java interview questions.
                        2. Keep explanations simple and clear.
                        3. Avoid duplicate questions.
                        4. Adjust difficulty according to the candidate's experience.
                        5. Focus on backend Java development topics.
                        """)
                // User message: Actual request
                .user(message)
                //send req to gemini
                .call()
                //Extract response
                .content();
    }

    public InterviewQuestionsResponse generateQuestions(String message){
        InterviewQuestionsResponse interviewQuestionsResponse = chatClient.prompt()
                .system("""
                    You are an experienced Java technical interviewer.

                    Generate Java interview questions based on the user's request.

                    Return the response in the following structure:
                    {
                      "questions": [
                        {
                          "question": "Question text",
                          "difficulty": "BEGINNER",
                          "answer": "Detailed but simple answer"
                        }
                      ]
                    }

                    Rules:
                    1. Return only the structured response.
                    2. Do not include Markdown or additional explanations outside the response.
                    3. Each question must have a clear answer.
                    4. Difficulty must be BEGINNER, INTERMEDIATE, or ADVANCED.
                    5. Avoid duplicate questions.
                    """)
                .user(message)
                .call()
                .entity(InterviewQuestionsResponse.class);
        //Validate the response generated by the GEMINI
        Set<ConstraintViolation<InterviewQuestionsResponse>> violations =
                validator.validate(interviewQuestionsResponse);

        //If validation errors exists, throw an exception
        if(!violations.isEmpty()){
            //Means that if the generated response violates our validation rules, we stop normal processing and throw an exception.
            throw new ConstraintViolationException(violations);
        }

        return interviewQuestionsResponse;
    }
}
